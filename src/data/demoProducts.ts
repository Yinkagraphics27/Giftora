export const getProductById = (id: string): DemoProduct | undefined => {
  return demoProducts.find((product) => product.id === id);
};

export const getProductsByCategory = (category: string): DemoProduct[] => {
  if (category === "all") return demoProducts;
  return demoProducts.filter((product) => product.category === category);
};

export const getProductsByVendor = (vendorId: string): DemoProduct[] => {
  return demoProducts.filter((product) => product.vendorId === vendorId);
};

// Get products only from vendors with active subscriptions
export const getActiveProducts = (): DemoProduct[] => {
  const { getActiveVendors } = require("./demoVendors");
  const activeVendorIds = new Set(getActiveVendors().map((v: { id: string }) => v.id));
  return demoProducts.filter((product) => activeVendorIds.has(product.vendorId));
};
